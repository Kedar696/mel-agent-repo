#!/usr/bin/env python
"""Regenerate every published number from a fresh run. Owner: P5 (README results section).

  python scripts/readme_numbers.py                      print the numbers
  python scripts/readme_numbers.py --write              also rewrite the README results section
                                                        and docs/results/scorecard.md (offline scorecard)
  python scripts/readme_numbers.py --write --record "what changed"
                                                        also append this run to docs/results/eval_history.jsonl

Numbers in the README and slides come from here, never typed by hand (team contract).
"""
import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from mel.config import PACK_DATA, ROOT
from mel.data import load_golden, load_insights
from mel.evaluation import score_golden, run_scorecard, load_history, record_run

README = ROOT / "README.md"
SCORECARD = ROOT / "docs" / "results" / "scorecard.md"
START, END = "<!-- results:start -->", "<!-- results:end -->"


def pct(x):
    return f"{x:.1%}"


def gather():
    mock = score_golden()
    full_path = PACK_DATA / "golden_set.jsonl"
    full = score_golden(load_golden(full_path)) if full_path.exists() else None
    ins_path = PACK_DATA / "insights.jsonl"
    card = run_scorecard(load_insights(ins_path if ins_path.exists() else None))
    return mock, full, card


def golden_line(label, r):
    return (f"{label}: n={r['n']}  decision={pct(r['decision_acc'])}  rule={pct(r['rule_acc'])}  "
            f"channel={pct(r['channel_acc'])}  window={pct(r['window_acc'])}  "
            f"item_sim={r['item_similarity_avg']:.2f}  misses={len(r['misses'])}")


def card_line(c):
    return (f"Batch: insights={c['n_insights']}  surveyed={c['n_surveyed']}  files={c['n_survey_files']}  "
            f"format={pct(c['format_pass'])}  safety={pct(c['safety_pass'])}  "
            f"failed_but_scheduled={c['failed_but_scheduled']}  relevance={c['relevance_avg']:.2f}  "
            f"speed={c['ms_per_insight']} ms/insight ({c['batch_seconds']} s total)")


def results_md(mock, full, card) -> str:
    g = full or mock
    rows = [("Decision (survey or not)", pct(g["decision_acc"]), pct(mock["decision_acc"])),
            ("Rule (which of R1–R8)", pct(g["rule_acc"]), pct(mock["rule_acc"])),
            ("First channel", pct(g["channel_acc"]), pct(mock["channel_acc"])),
            ("Send window (exact match)", pct(g["window_acc"]), pct(mock["window_acc"])),
            ("Item similarity (keyword overlap)", f"{g['item_similarity_avg']:.2f}", f"{mock['item_similarity_avg']:.2f}"),
            ("Misses", str(len(g["misses"])), str(len(mock["misses"])))]
    out = [f"**Answer key** (golden set). Full pack: {g['n']} rows · mock subset: {mock['n']} rows.", "",
           "| Measure | Full pack | Mock |", "|---|---|---|"]
    out += [f"| {a} | {b} | {c} |" for a, b, c in rows]
    out += ["", f"**Every survey we write** ({card['n_insights']:,} insights → {card['n_surveyed']:,} surveys, "
                f"{card['n_survey_files']:,} files in Hindi + English).", "",
            "| Measure | Result |", "|---|---|",
            f"| Format (schema, 1–3 tap items, right language) | {pct(card['format_pass'])} |",
            f"| Safety (no new advice, no personal info) | {pct(card['safety_pass'])} |",
            f"| Failing surveys handed to the scheduler | {card['failed_but_scheduled']} |",
            f"| Relevance (P4's baseline score, 0–1) | {card['relevance_avg']:.2f} |",
            f"| Speed | {card['ms_per_insight']} ms per insight · {card['batch_seconds']} s for the batch |"]
    if g["misses"]:
        out += ["", "Misses: " + ", ".join(f"{m['golden_id']} (expected {m['expected']}, got {m['got']})"
                                          for m in g["misses"])]
    out += ["", "_Generated by `python scripts/readme_numbers.py --write`. Do not edit by hand._"]
    return "\n".join(out)


def history_md() -> str:
    hist = load_history()
    if not hist:
        return "_No recorded runs yet. Record one with `--record \"label\"`._"
    out = ["| Run | When | Commit | What changed | Decision | Rule | Window | Item sim | Misses |",
           "|---|---|---|---|---|---|---|---|---|"]
    for h in hist:
        out.append(f"| {h['run']} | {h['at'][:16].replace('T', ' ')} | `{h['commit']}`{'*' if h.get('uncommitted_changes') else ''} "
                   f"| {h['label']} | {pct(h['decision_acc'])} | {pct(h['rule_acc'])} | {pct(h['window_acc'])} "
                   f"| {h['item_similarity_avg']:.2f} | {h['misses']} |")
    out.append("")
    out.append("`*` = run had uncommitted changes.")
    return "\n".join(out)


def write_readme(body: str):
    text = README.read_text(encoding="utf-8")
    block = f"{START}\n{body}\n{END}"
    if START in text and END in text:
        text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    else:
        text = text.rstrip() + "\n\n## Results\n" + block + "\n"
    README.write_text(text, encoding="utf-8")


def write_scorecard(body: str, card: dict):
    ex = card["examples"]
    fails = "\n".join(f"- {e['insight_id']} ({e['language']}): {'; '.join(e['problems'])}" for e in ex) or "None."
    SCORECARD.parent.mkdir(parents=True, exist_ok=True)
    SCORECARD.write_text(
        "# MEL Survey Agent: offline scorecard\n\n"
        "Backup for the demo: open this file if the app won't start. Same numbers as the Evaluation tab.\n\n"
        f"{body}\n\n## Run history (hill-climb)\n\n{history_md()}\n\n"
        f"## Surveys that failed format or safety (first {len(ex)})\n\n{fails}\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", action="store_true", help="rewrite README results + offline scorecard")
    ap.add_argument("--record", metavar="LABEL", help="append this run to the history, with a label")
    a = ap.parse_args()

    mock, full, card = gather()
    print(golden_line("Mock", mock))
    print(golden_line("Full", full) if full else f"Full pack not found at {PACK_DATA}")
    print(card_line(card))
    if a.record:
        row = record_run(a.record, full or mock, card)
        print(f"Recorded run {row['run']}: {a.record}")
    if a.write:
        body = results_md(mock, full, card)
        write_readme(body)
        write_scorecard(body, card)
        print(f"Wrote {README.relative_to(ROOT)} and {SCORECARD.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
